// Maps every factual claim on the site to its source and checks it against private/main.md.
// Writes private/CLAIMS.md (kept out of git because it quotes main.md).
// Usage: node scripts/claims.mjs
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";
import YAML from "yaml";

const main = fs.readFileSync("private/main.md", "utf8").split(/\r?\n/);
const norm = (s) => s.toLowerCase().replace(/[*`_]/g, "").replace(/[–—-]/g, "-").replace(/\s+/g, " ").trim();
const mainNorm = norm(main.join(" "));

function lines(source) {
    const m = /main\.md:(\d+)(?:-(\d+))?/.exec(source || "");
    if (!m) return null;
    const a = Number(m[1]);
    const b = Number(m[2] || m[1]);
    return norm(main.slice(a - 1, b).join(" "));
}

/** verbatim | tokens | missing | not main.md */
function check(text, source) {
    const span = lines(source);
    if (!span) return source ? "outside main.md" : "no source";
    const t = norm(text);
    if (span.includes(t) || mainNorm.includes(t)) return "verbatim";
    const tokens = (text.match(/\d+(?:\.\d+)?%?|[A-Za-z][A-Za-z0-9+#.-]{3,}/g) || []).map((x) => x.toLowerCase().replace(/\.$/, ""));
    const missing = tokens.filter((k) => !span.includes(k) && !mainNorm.includes(k));
    return missing.length === 0 ? "key terms match" : `CHECK: ${[...new Set(missing)].slice(0, 6).join(", ")}`;
}

const rows = [];
const add = (where, claim, source) => rows.push({ where, claim, source: source || "", status: check(claim, source) });

const profile = YAML.parse(fs.readFileSync("content/profile.yaml", "utf8"));
add("profile", profile.name, "main.md:15");
add("profile", profile.email, "main.md:17");
add("profile", profile.links.linkedin, "main.md:19");
add("profile", profile.links.github, "main.md:20");
add("profile", profile.links.website, "main.md:21");
add("profile", profile.status, "brief §1");
for (const e of profile.education) {
    add("education", `${e.degree}`, e.source);
    add("education", `${e.period}`, e.source);
    add("education", e.detail, e.source);
}
for (const c of profile.coursework.items) add("coursework", c, profile.coursework.source);
for (const a of [...profile.achievements, ...profile.certifications]) add("achievements", a.text, a.source);

const exp = YAML.parse(fs.readFileSync("content/experience.yaml", "utf8")).entries;
for (const e of exp) {
    add(`experience/${e.id}`, `${e.role} — ${e.org}`, e.source);
    for (const p of e.points) add(`experience/${e.id}`, p, e.source);
}

for (const g of YAML.parse(fs.readFileSync("content/skills.yaml", "utf8")).groups) add("skills", `${g.name}: ${g.items.join(", ")}`, g.source);

for (const f of fs.readdirSync("content/projects").filter((x) => x.endsWith(".mdx"))) {
    const { data, content } = matter(fs.readFileSync(path.join("content/projects", f), "utf8"));
    const src = (data.sources || [])[0] || "";
    const where = `projects/${f.replace(".mdx", "")}`;
    add(where, data.title, src);
    if (data.stack?.length) add(where, data.stack.join(", "), src);
    if (data.scope) {
        const r = { where, claim: `Scope & limits: ${data.scope}`, source: data.scope_source || src, status: check(data.scope, src) };
        if (r.status.startsWith("CHECK") && data.scope_source) r.status = "repo source (see Source)";
        rows.push(r);
    }
    for (const m of data.metrics || []) add(where, `${m.value} ${m.label}`, m.source);
    let section = "";
    for (const l of content.split(/\r?\n/)) {
        if (l.startsWith("## ")) section = l.slice(3);
        if (l.startsWith("- ")) add(where, l.slice(2), section.startsWith("From the PyATPG") ? "py-atpg-comb/README.md" : src);
    }
}

const bad = rows.filter((r) => r.status.startsWith("CHECK"));
const out = [
    "# Claims on the site → source",
    "",
    `Generated by scripts/claims.mjs on ${new Date().toISOString().slice(0, 10)}. ${rows.length} claims; ${bad.length} need a look.`,
    "",
    "Status: **verbatim** = text appears in main.md; **key terms match** = every number and term appears in the cited lines; **CHECK** = listed words not found; **outside main.md** = sourced from the brief or a repo README.",
    "",
    "| Where | Claim | Source | Status |",
    "|---|---|---|---|",
    ...rows.map((r) => `| ${r.where} | ${r.claim.replace(/\|/g, "\\|")} | ${r.source} | ${r.status} |`),
    "",
];
fs.writeFileSync("private/CLAIMS.md", out.join("\n"));
console.log(`${rows.length} claims, ${rows.filter((r) => r.status === "verbatim").length} verbatim, ${rows.filter((r) => r.status === "key terms match").length} key terms, ${bad.length} CHECK, ${rows.filter((r) => r.status === "outside main.md").length} outside main.md`);
for (const r of bad) console.log(" ", r.where, "|", r.claim.slice(0, 70), "|", r.status);
